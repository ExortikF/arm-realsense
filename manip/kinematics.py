r"""
Прямая и обратная кинематика руки SO-ARM100 (5 DOF + захват).

Структура: поворот основания + три звена в одной вертикальной плоскости
+ вращение кисти.

        q3 (elbow)
          o------------o  q4 (wrist)
         /              \
    L2  /                \ L4  -> схват
       /                  \
      o q2 (shoulder)      * TCP (x, y, z)
      |
      | L1
      |
    ==o== q1 (поворот вокруг вертикали Z)

Система координат робота:
    X — вперёд от основания
    Y — влево
    Z — вверх
    начало — в оси поворота основания, на уровне стола.

Ключевая идея, которая делает 5-осевую ОК аналитической:
q1 отвечает ТОЛЬКО за азимут, а q2, q3, q4 работают в плоскости,
повёрнутой на q1. То есть 3D-задача разваливается на две простые:
одна тригонометрическая функция + плоская задача про два звена.
Никакой численной оптимизации не нужно.

Плата за 5 осей вместо 6: ориентацию схвата задать полностью нельзя.
Свободен только УГОЛ НАКЛОНА схвата в вертикальной плоскости (pitch),
он же `pitch` в аргументах. Рыскание жёстко связано с q1.
"""

import math
import numpy as np


class ArmGeometry:
    """
    Длины звеньев В МЕТРАХ.

    !!! ЗАМЕРЬТЕ СВОИ ЛИНЕЙКОЙ. Значения ниже — прикидка по SO-ARM100,
    ошибка в 5 мм на L3 даёт ~сантиметр промаха на краю рабочей зоны.

    Что мерить:
      L1 — от стола до оси сервы 2 (плеча)
      L2 — между осями серв 2 и 3
      L3 — между осями серв 3 и 4
      L4 — от оси сервы 4 до точки схвата (TCP), при закрытых губках
    """

    def __init__(self, L1=0.055, L2=0.117, L3=0.135, L4=0.100):
        self.L1 = L1
        self.L2 = L2
        self.L3 = L3
        self.L4 = L4

    @property
    def reach_max(self):
        return self.L2 + self.L3

    @property
    def reach_min(self):
        return abs(self.L2 - self.L3)


def forward(geo, q):
    """
    Прямая кинематика: углы (радианы) -> положение схвата (метры).

    q = [q1 pan, q2 shoulder, q3 elbow, q4 wrist]
    Углы q2, q3, q4 — относительные (каждый отсчитывается от предыдущего
    звена), потому что именно так устроены сами сервы.

    Держите эту функцию под рукой: она — способ проверить ОК.
    forward(inverse(target)) должно дать target. Если не даёт —
    ошибка в геометрии или в знаках, а не в железе.
    """
    q1, q2, q3, q4 = q[0], q[1], q[2], q[3]

    a2 = q2               # абсолютный угол первого звена к горизонту
    a3 = q2 + q3          # абсолютный угол предплечья
    a4 = q2 + q3 + q4     # абсолютный угол схвата

    r = geo.L2 * math.cos(a2) + geo.L3 * math.cos(a3) + geo.L4 * math.cos(a4)
    z = geo.L1 + geo.L2 * math.sin(a2) + geo.L3 * math.sin(a3) + geo.L4 * math.sin(a4)

    return np.array([r * math.cos(q1), r * math.sin(q1), z])


def inverse(geo, target, pitch=-math.pi / 2, elbow_up=True):
    """
    Обратная кинематика.

    target — (x, y, z) в метрах, в системе координат робота.
    pitch  — желаемый наклон схвата к горизонтали, радианы:
                -pi/2  смотрит вертикально ВНИЗ (брать со стола)
                 0     смотрит горизонтально ВПЕРЁД
    elbow_up — какое из двух решений брать («локоть вверх» / «вниз»).
               Решений всегда два; переключение между ними на ходу
               выглядит как резкий бросок руки, поэтому фиксируем одно.

    Возвращает (углы[4], ok):
      ok=False означает, что точка вне зоны достижимости и была
      ПРИЖАТА к её границе. Это не ошибка, это нормальный режим работы:
      человек машет рукой шире, чем робот дотягивается. Важно, что
      при этом мы возвращаем ближайшую достижимую позу, а не мусор
      из acos(1.7) — иначе получим NaN и рука встанет колом.
    """
    x, y, z = float(target[0]), float(target[1]), float(target[2])
    ok = True

    # --- 1. Азимут. Одна строка — и 3D-задача стала плоской.
    q1 = math.atan2(y, x)

    # --- 2. Переходим в плоскость (r, h) этого азимута.
    r = math.hypot(x, y)
    h = z - geo.L1

    # --- 3. Снимаем последнее звено: считаем, где должно быть ЗАПЯСТЬЕ.
    #        Схват под углом pitch и длиной L4 — значит запястье
    #        отстоит от цели на L4 в противоположную сторону.
    rw = r - geo.L4 * math.cos(pitch)
    hw = h - geo.L4 * math.sin(pitch)

    # --- 4. Плоская задача о двух звеньях (теорема косинусов).
    d = math.hypot(rw, hw)

    # Прижимаем к кольцу достижимости. 0.999 — чтобы не вставать
    # ровно в вытянутую сингулярность, где ОК теряет устойчивость
    # (около неё микрошум в цели даёт огромные скачки углов).
    d_max = (geo.L2 + geo.L3) * 0.999
    d_min = abs(geo.L2 - geo.L3) * 1.001
    if d > d_max or d < d_min:
        ok = False
        d_clamped = min(max(d, d_min), d_max)
        if d < 1e-6:
            rw, hw, d = d_clamped, 0.0, d_clamped
        else:
            k = d_clamped / d
            rw, hw, d = rw * k, hw * k, d_clamped

    cos_q3 = (d * d - geo.L2 ** 2 - geo.L3 ** 2) / (2 * geo.L2 * geo.L3)
    cos_q3 = max(-1.0, min(1.0, cos_q3))
    q3 = math.acos(cos_q3)
    if elbow_up:
        q3 = -q3

    # угол на запястье минус поправка на «раскрытие» треугольника
    q2 = math.atan2(hw, rw) - math.atan2(
        geo.L3 * math.sin(q3), geo.L2 + geo.L3 * math.cos(q3)
    )

    # --- 5. Кисть добирает остаток до нужного наклона схвата.
    q4 = pitch - q2 - q3

    return np.array([q1, q2, q3, q4]), ok


def clamp_to_workspace(geo, target, margin=0.01):
    """
    Прижать точку к рабочей зоне ДО вызова inverse().

    Зачем отдельно, если inverse и так прижимает: здесь мы правим
    саму цель, и её можно показать на экране. Пользователь видит,
    что рука упёрлась в предел, а не гадает, почему она перестала
    слушаться.
    """
    x, y, z = float(target[0]), float(target[1]), float(target[2])
    h = z - geo.L1
    r = math.hypot(x, y)

    d = math.hypot(r, h)
    d_max = geo.reach_max + geo.L4 - margin
    d_min = geo.reach_min + margin

    if d > d_max or d < d_min:
        k = min(max(d, d_min), d_max) / max(d, 1e-6)
        r, h = r * k, h * k
        ang = math.atan2(y, x)
        return np.array([r * math.cos(ang), r * math.sin(ang), h + geo.L1]), False

    return np.array([x, y, z]), True
